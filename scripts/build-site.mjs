import { rm, mkdir, copyFile, cp, writeFile, readFile, stat } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve,dirname,basename,join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { profiles } from "../src/data/profiles.js";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const dist=resolve(root,"dist");
const dest=resolve(dist,"assets/optimized");
await rm(dist,{recursive:true,force:true});
await mkdir(dest,{recursive:true});
await mkdir(resolve(dist,"assets/images"),{recursive:true});
await cp(resolve(root,"src"),resolve(dist,"src"),{recursive:true});
for(const file of ["index.html","styles.css"]){
 await copyFile(resolve(root,file),resolve(dist,file));
}
await copyFile(resolve(root,"assets/images/all-animals_resized.png"),resolve(dist,"assets/images/all-animals_resized.png"));
await writeFile(resolve(dist,".nojekyll"),"");
const manifest={};
const report={schemaVersion:"1.0.0",profiles:[],totals:{webpBytes:0,avifBytes:0},budgets:{webp640Bytes:256000,avif640Bytes:200000}};
const sizes=[320,640];
for(const [type,p] of Object.entries(profiles)){
 const name=basename(p.image,".png");
 const source=resolve(root,p.image);
 const srcsets={webp:[],avif:[]};
 const stats={type,variants:[]};
 for(const format of ["webp","avif"]){
  for(const width of sizes){
   const filename=name+"-"+width+"."+format;
   const output=resolve(dest,filename);
   const coder=sharp(source).rotate().resize({width,withoutEnlargement:true});
   if(format==="avif") await coder.avif({quality:49,effort:2}).toFile(output);
   else await coder.webp({quality:73,effort:4}).toFile(output);
   const bytes=(await stat(output)).size;
   const relative="./assets/optimized/"+filename;
   srcsets[format].push(relative+" "+width+"w");
   report.totals[format+"Bytes"]+=bytes;
   const sha256=createHash("sha256").update(await readFile(output)).digest("hex");
   stats.variants.push({format,width,bytes,path:relative,sha256});
   if(width===640&&bytes>report.budgets[format+"640Bytes"])
    throw new Error("Image budget exceeded: "+type+" "+format+" "+bytes);
  }
 }
 manifest[type]={avif:srcsets.avif.join(", "),webp:srcsets.webp.join(", "),
  fallback:"./assets/optimized/"+name+"-640.webp"};
 report.profiles.push(stats);
}
const manifestSource=[
 "// Generated by scripts/build-site.mjs; not the source-of-truth.",
 "export const imageManifest = "+JSON.stringify(manifest,null,2)+";",
 ""
].join("\n");
await writeFile(resolve(dist,"src/data/image-manifest.js"),manifestSource);
await writeFile(resolve(dist,"build-report.json"),JSON.stringify(report,null,2)+"\n");
console.log("Site built at dist/; images:",report.profiles.length,"WebP bytes:",report.totals.webpBytes,"AVIF bytes:",report.totals.avifBytes);
