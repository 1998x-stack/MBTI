import { readFile, stat, readdir } from "node:fs/promises";
import { resolve,dirname } from "node:path";
import { fileURLToPath } from "node:url";
const dist=resolve(dirname(fileURLToPath(import.meta.url)),"../dist");
const report=JSON.parse(await readFile(resolve(dist,"build-report.json"),"utf8"));
if(report.profiles.length!==16)throw new Error("Expected 16 optimized illustrations");
for(const profile of report.profiles){
 if(profile.variants.length!==4)throw new Error("Missing image variants for "+profile.type);
 for(const v of profile.variants){
  if((await stat(resolve(dist,v.path))).size!==v.bytes)throw new Error("Mismatched generated bytes: "+v.path);
 }
}
for(const path of ["index.html","styles.css","src/app.js","src/data/questions.js","src/data/image-manifest.js","assets/images/all-animals_resized.png"]){
 const size=(await stat(resolve(dist,path))).size;
 if(size===0)throw new Error("Empty build file "+path);
}
const originals=(await readdir(resolve(dist,"assets/images"))).filter(p=>p.endsWith(".png"));
if(originals.length!==1||originals[0]!=="all-animals_resized.png")
 throw new Error("Published dist must exclude oversized original result images");
const html=await readFile(resolve(dist,"index.html"),"utf8");
if(html.includes('src="/assets/')||html.includes('href="/assets/'))
 throw new Error("Absolute asset URL is not GitHub Pages project-path safe");
console.log("Verified published dist:",report.profiles.length,"profiles,",report.profiles.length*4,"optimized files");
